export type Language = keyof typeof translations
export type TranslationKey = keyof typeof translations.fr
export type I18nContextValue = {
  language: Language
  t: (key: TranslationKey, variables?: Record<string, string | number>) => string
}

export function translate(language: Language, key: TranslationKey, variables: Record<string, string | number> = {}) {
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    translations[language][key] as string,
  )
}

export function browserLanguage(): Language {
  if (typeof navigator === 'undefined') return 'fr'
  const requested = navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const language of requested) {
    const base = language.toLocaleLowerCase().split('-')[0]
    if (base === 'fr' || base === 'en') return base
  }
  return 'fr'
}

export const I18nContext = createContext<I18nContextValue>({
  language: 'fr',
  t: (key, variables) => translate('fr', key, variables),
})

export function useTranslation() {
  return useContext(I18nContext)
}
